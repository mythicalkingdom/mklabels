#!/usr/bin/env python3
"""Generate src/layouts.inc from the gLabels Avery US-Letter template file.

Source data (GPL-3.0-or-later, from the gLabels project):
  https://sources.debian.org/data/main/g/glabels/3.4.1-6/templates/avery-us-templates.xml

Usage: tools/gen_layouts.py avery-us-templates.xml > src/layouts.inc
"""
import re
import sys
import xml.etree.ElementTree as ET

PT = {"in": 72.0, "mm": 72.0 / 25.4, "cm": 72.0 / 2.54, "pt": 1.0, "": 1.0}


def pts(s):
    m = re.fullmatch(r"\s*([0-9.]+)\s*([a-z]*)\s*", s)
    return float(m.group(1)) * PT[m.group(2)]


def num(v):
    return ("%.4f" % v).rstrip("0").rstrip(".") or "0"


def pas(s):
    return "'" + s.replace("'", "''") + "'"


root = ET.parse(sys.argv[1]).getroot()
base = {}
for t in root.iter("Template"):
    part = t.get("part")
    if t.get("equiv"):
        continue
    lab = None
    for kind in ("Label-rectangle", "Label-round"):
        lab = t.find(kind)
        if lab is not None:
            break
    if lab is None:                       # CD labels etc. are not supported
        continue
    lay = lab.find("Layout")
    if kind == "Label-round":
        w = h = 2 * pts(lab.get("radius"))
    else:
        w, h = pts(lab.get("width")), pts(lab.get("height"))
    dx, dy = pts(lay.get("dx")), pts(lay.get("dy"))
    base[part] = dict(
        desc=t.get("_description", ""),
        cols=int(lay.get("nx")), rows=int(lay.get("ny")),
        w=w, h=h, left=pts(lay.get("x0")), top=pts(lay.get("y0")),
        hs=dx - w if int(lay.get("nx")) > 1 else 0.0,
        vs=dy - h if int(lay.get("ny")) > 1 else 0.0)

entries = dict(base)
for t in root.iter("Template"):
    eq = t.get("equiv")
    if eq and eq in base:
        e = dict(base[eq])
        e["desc"] = base[eq]["desc"]
        entries[t.get("part")] = e

def key(p):
    return [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", p)]

print("{ Generated by tools/gen_layouts.py from the gLabels Avery US-Letter")
print("  templates (GPL-3.0-or-later).  Do not edit by hand.  All values in points. }")
print("const")
print("  LayoutCount = %d;" % len(entries))
print("  Layouts: array[0..%d] of TLayout = (" % (len(entries) - 1))
rows = []
for p in sorted(entries, key=key):
    e = entries[p]
    rows.append("    (Part: %s; Desc: %s; Cols: %d; Rows: %d; W: %s; H: %s; "
                "Left: %s; Top: %s; HSpace: %s; VSpace: %s)" % (
                    pas(p), pas(e["desc"]), e["cols"], e["rows"], num(e["w"]),
                    num(e["h"]), num(e["left"]), num(e["top"]), num(e["hs"]),
                    num(e["vs"])))
print(",\n".join(rows))
print("  );")
